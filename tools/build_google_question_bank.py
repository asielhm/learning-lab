"""Generate Google's scoring banks and the public readiness manifest from every revision bank."""
import hashlib,json,sys,zipfile,subprocess
sys.dont_write_bytecode=True
from pathlib import Path
from html.parser import HTMLParser
from validate_questions import BANKS

ROOT=Path(__file__).resolve().parent.parent
from brand import apply_branding
apply_branding()
class RevisionPage(HTMLParser):
    def __init__(self):super().__init__();self.attrs=None
    def handle_starttag(self,tag,attributes):
        values=dict(attributes)
        if values.get('id')=='revision-app':self.attrs=values

# Derive courses from the actual student wrappers, not filename conventions.
wrappers={};preparation_paths={}
for page in (ROOT/'activities').rglob('revision.html'):
    parser=RevisionPage();parser.feed(page.read_text());attrs=parser.attrs
    if not attrs or not attrs.get('data-bank'):continue
    path=(page.parent/attrs['data-bank']).resolve()
    assert path.parent==ROOT/'assets/revision/questions',f'Unexpected bank path: {page}'
    course=attrs.get('data-course','Year 9 Science')
    preparation_paths[attrs['data-topic']]=str((page.parent/'prepare.html').relative_to(ROOT))
    previous=wrappers.setdefault(path.name,course)
    assert previous==course,f'Conflicting course wrappers: {page}'
    if attrs.get('data-recording')=='auto':assert attrs['data-topic']==BANKS[path.name],f'Auto-recording topic differs from bank: {page}'
banks={};metadata=[]
for filename,topic in BANKS.items():
    bank=json.loads((ROOT/'assets/revision/questions'/filename).read_text())
    assert bank['topicId']==topic
    course=wrappers[filename]
    questions={q['id']:{key:q[key] for key in ('prompt','category','difficulty','options','answer')} for q in bank['questions']}
    canonical={'course':course,'questions':questions}
    signature=hashlib.sha256(json.dumps(canonical,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode()).hexdigest()
    banks[topic]={**canonical,'title':bank['title'],'categories':bank['categories'],'signature':signature}
    metadata.append(dict(topic=topic,course=course,title=bank['title'],questionCount=len(questions),signature=signature))
manifest=dict(protocol=3,release='all-courses-1',questionCount=sum(b['questionCount'] for b in metadata),banks=metadata)
output='// Generated by tools/build_google_question_bank.py; no student records or secrets.\n'
output+='var RECORDING_MANIFEST_ = '+json.dumps(manifest,ensure_ascii=False,indent=2)+';\n'
output+='var QUESTION_BANKS_ = '+json.dumps(banks,ensure_ascii=False,indent=2)+';\n'
games=json.loads(subprocess.check_output(['node',str(ROOT/'tools/export_game_catalog.mjs')],text=True))
game_manifest={'protocol':1,'games':[{key:game[key] for key in ('id','title','course','topic','signature')}|{'roundCount':len(game['rounds']),'preparation':preparation_paths[game['topic']]} for game in games.values()]}
output+='var GAME_MANIFEST_ = '+json.dumps(game_manifest,ensure_ascii=False,indent=2)+';\n'
output+='var GAME_CATALOG_ = '+json.dumps(games,ensure_ascii=False,indent=2)+';\n'
(ROOT/'assets/records/games.json').write_text(json.dumps(game_manifest,ensure_ascii=False,indent=2)+'\n')
(ROOT/'google-apps-script/QuestionBank.gs').write_text(output)
(ROOT/'assets/records/banks.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(f"Generated {len(banks)} Apps Script banks / {manifest['questionCount']} questions and the public readiness manifest.")

from build_assessment_preparation import apply_preparation
apply_preparation()

# A deterministic bundle makes the owner-side update one download.
with zipfile.ZipFile(ROOT/'google-apps-script/learning-lab-dashboard-update.zip','w',compression=zipfile.ZIP_DEFLATED) as archive:
    for filename in ('Code.gs','QuestionBank.gs','Dashboard.html','UPDATE.md'):
        info=zipfile.ZipInfo(filename,date_time=(2026,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16
        archive.writestr(info,(ROOT/'google-apps-script'/filename).read_bytes())
