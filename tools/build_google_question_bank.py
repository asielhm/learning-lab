"""Keep the private Apps Script marker aligned with the published revision banks."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
banks = {}
for filename in ("algebra", "circulatory", "breathing", "gas-laws"):
    bank = json.loads((ROOT / "assets/revision/questions" / f"{filename}.json").read_text())
    banks[bank["topicId"]] = {
        "course": "Year 7 Maths" if filename == "algebra" else "Year 9 Science",
        "questions": {
            q["id"]: {key: q[key] for key in ("prompt", "category", "difficulty", "options", "answer")}
            for q in bank["questions"]
        },
    }
output = "// Generated by tools/build_google_question_bank.py; contains no student records or secrets.\nvar QUESTION_BANKS_ = " + json.dumps(banks, ensure_ascii=False, indent=2) + ";\n"
(ROOT / "google-apps-script/QuestionBank.gs").write_text(output)
print(f"Apps Script bank generated: {sum(len(b['questions']) for b in banks.values())} questions.")
